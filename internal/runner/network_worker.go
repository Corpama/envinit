package runner

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"time"
)

const networkWorkerRequest = "/var/lib/envinit/network-worker.json"
const networkWorkerResult = "/var/lib/envinit/network-worker-result.json"
const networkWorkerLog = "/var/lib/envinit/network-worker.log"

type networkWorkerInput struct {
	App          *App               `json:"app"`
	Bindings     []interfaceBinding `json:"bindings"`
	SourceRecord json.RawMessage    `json:"source_record,omitempty"`
	HasSource    bool               `json:"has_source"`
}

type networkWorkerOutput struct {
	Error string `json:"error,omitempty"`
}

// Only the reviewed, non-interactive network stage is detached. Later stages
// still obey the caller's selected stages and existing interactive semantics.
func (a *App) runDetachedNetworkStage() error {
	if err := a.beginNetworkTransaction(); err != nil {
		return err
	}
	bindings, err := a.confirmedNICBindings()
	if err != nil {
		return err
	}
	if _, err := exec.LookPath("systemd-run"); err != nil {
		return fmt.Errorf("SSH network apply requires systemd-run for connection-independent execution: %w", err)
	}
	source, err := json.Marshal(a.applySourceRecord)
	if err != nil {
		return err
	}
	request := networkWorkerInput{App: a, Bindings: bindings, SourceRecord: source, HasSource: a.hasApplySourceRecord}
	if err := a.writeNetworkState(networkWorkerRequest, request); err != nil {
		return err
	}
	if err := os.Remove(a.targetPath(networkWorkerResult)); err != nil && !os.IsNotExist(err) {
		return err
	}
	executable, err := os.Executable()
	if err != nil {
		return err
	}
	a.logf("network apply runs independently of SSH; log=%s result=%s", networkWorkerLog, networkWorkerResult)
	// Keep the caller lock until systemd has accepted the queued unit. The
	// worker then acquires the same lock after this function hands it over.
	err = a.runCmdTimeout(probeCommandTimeout, "", nil, "systemd-run", "--unit=envinit-network-apply", "--no-block", "--collect", "--property=Type=exec", executable, "__network-worker")
	if err != nil {
		return fmt.Errorf("start detached network worker: %w", err)
	}
	if a.applyUnlock != nil {
		a.applyUnlock()
		a.applyUnlock = nil
	}
	// Do not wait on systemd-run's client process. Poll a root-owned result file;
	// the worker continues if this SSH process disappears.
	deadline := time.NewTimer(30 * time.Minute)
	defer deadline.Stop()
	for {
		if _, statErr := os.Stat(a.targetPath(networkWorkerResult)); statErr == nil {
			break
		}
		select {
		case <-deadline.C:
			return fmt.Errorf("network worker did not finish within 30m; inspect %s", networkWorkerLog)
		case <-time.After(500 * time.Millisecond):
		}
	}
	// The worker owns the lock until completion. Never continue subsequent
	// stages without reacquiring it. The result is written just before the
	// worker releases the lock, so retry the non-blocking lock acquisition.
	var unlock func()
	var lockErr error
	for {
		unlock, lockErr = acquireExecutionLock(a.targetPath("/var/lib/envinit/apply.lock"))
		if lockErr == nil {
			break
		}
		select {
		case <-deadline.C:
			return fmt.Errorf("network worker result exists but apply lock is still held; inspect %s: %w", networkWorkerLog, lockErr)
		case <-time.After(100 * time.Millisecond):
		}
	}
	a.applyUnlock = unlock
	data, readErr := os.ReadFile(a.targetPath(networkWorkerResult))
	if readErr != nil {
		return fmt.Errorf("network worker result unavailable: %w", readErr)
	}
	var result networkWorkerOutput
	if e := json.Unmarshal(data, &result); e != nil {
		return e
	}
	if result.Error != "" {
		return fmt.Errorf("network worker failed: %s; see %s", result.Error, networkWorkerLog)
	}
	if err != nil {
		return err
	}
	a.udevRulesPersisted = true
	a.networkTransaction = nil
	return nil
}

// RunNetworkWorker is an internal CLI entry, not a user-selectable apply mode.
// It accepts no arbitrary path or commands; root-owned input is generated by
// the normal reviewed apply workflow.
func RunNetworkWorker() error {
	if os.Geteuid() != 0 {
		return fmt.Errorf("network worker requires root")
	}
	// systemd may start the unit before the SSH-side parent has handed over
	// the lock. Wait for that handoff instead of treating the expected overlap
	// as a worker failure.
	var unlock func()
	var err error
	deadline := time.NewTimer(60 * time.Second)
	defer deadline.Stop()
	for {
		unlock, err = acquireExecutionLock("/var/lib/envinit/apply.lock")
		if err == nil {
			break
		}
		select {
		case <-deadline.C:
			return fmt.Errorf("network worker could not acquire apply lock: %w", err)
		case <-time.After(100 * time.Millisecond):
		}
	}
	defer unlock()
	info, err := os.Lstat(networkWorkerRequest)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Mode().Perm() != 0o600 {
		return fmt.Errorf("invalid network worker request permissions")
	}
	data, err := os.ReadFile(networkWorkerRequest)
	if err != nil {
		return err
	}
	var request networkWorkerInput
	if err := json.Unmarshal(data, &request); err != nil {
		return err
	}
	if request.App == nil {
		return fmt.Errorf("missing network worker configuration")
	}
	a := request.App
	if a.Root != "" && a.Root != "/" {
		return fmt.Errorf("network worker cannot apply an alternate root")
	}
	log, err := os.OpenFile(networkWorkerLog, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		return err
	}
	defer log.Close()
	a.Output = log
	a.DryRun = false
	a.networkWorker = true
	a.confirmedInterfaceBindings = request.Bindings
	a.interfaceBindingsConfirmed = true
	a.hasApplySourceRecord = request.HasSource
	if request.HasSource {
		if err := json.Unmarshal(request.SourceRecord, &a.applySourceRecord); err != nil {
			return err
		}
	}
	a.currentStageTimeout = a.Bundle.ApplyTimeouts.StageTimeout("network")
	err = a.runNetworkStage()
	result := networkWorkerOutput{}
	if err != nil {
		result.Error = err.Error()
	}
	if saveErr := a.writeNetworkState(networkWorkerResult, result); saveErr != nil {
		return saveErr
	}
	if err == nil {
		_ = os.Remove(filepath.Clean(networkWorkerRequest))
	}
	return err
}
